#!/usr/bin/env python3
"""Generate a multi-player docker-compose file for a hosted DVMCP lab.

Each player gets a dedicated container running all 15 challenge servers, so
mutable challenge state is never shared. A single gateway container serves
the dashboard and routes each player's playground requests to their container.

Usage:
    python3 deploy/generate_compose.py --players 20 > docker-compose.lab.yml
"""

import argparse

HEADER = """# Generated by deploy/generate_compose.py -- do not edit by hand.
# Players: {players}
#
#   caddy    : public TLS entrypoint (the only published ports)
#   dashboard: UI + API + database, routes players to their own containers
#   player-N : one full set of 15 challenge servers, internal network only

services:
  caddy:
    image: caddy:2
    container_name: dvmcp-caddy
    restart: unless-stopped
    ports:
      - "80:80"
      - "443:443"
    volumes:
      - ./deploy/Caddyfile:/etc/caddy/Caddyfile:ro
      - caddy-data:/data
      - caddy-config:/config
    depends_on:
      - dashboard

  dashboard:
    image: {image}
    container_name: dvmcp-dashboard
    restart: unless-stopped
    environment:
      - DVMCP_ROLE=gateway
      - DVMCP_MCP_POOL_SIZE={players}
      - DVMCP_MCP_HOST_TEMPLATE=dvmcp-player-{{slot}}
      - DVMCP_JWT_SECRET=${{DVMCP_JWT_SECRET:?set DVMCP_JWT_SECRET in .env}}
      - DVMCP_CORS_ORIGINS=${{DVMCP_PUBLIC_URL:-*}}
      - PYTHONUNBUFFERED=1
    volumes:
      - dvmcp-data:/app/dashboard/backend/data
"""

PLAYER = """
  player-{n}:
    image: {image}
    container_name: dvmcp-player-{n}
    hostname: dvmcp-player-{n}
    restart: unless-stopped
    environment:
      - DVMCP_ROLE=player
      - PYTHONUNBUFFERED=1
"""

FOOTER = """
volumes:
  dvmcp-data:
  caddy-data:
  caddy-config:
"""


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--players", type=int, default=20, help="number of player containers")
    parser.add_argument(
        "--image",
        default="dvmcp:lab",
        help="image tag to run (build once, reuse for every service)",
    )
    args = parser.parse_args()

    out = [HEADER.format(players=args.players, image=args.image)]
    for n in range(1, args.players + 1):
        out.append(PLAYER.format(n=n, image=args.image))
    out.append(FOOTER)
    print("".join(out))


if __name__ == "__main__":
    main()
